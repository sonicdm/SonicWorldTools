using System;
using System.IO;
using BepInEx.Logging;
using SonicWorldTools.Config;
using SonicWorldTools.Core;
using SonicWorldTools.Integration;
using SonicWorldTools.Modules.PrecisionAreaPipette;
using SonicWorldTools.Modules.PieceRepeater;

namespace SonicWorldTools.Install
{
	internal static class ToolInstallerBridge
	{
		/// <summary>
		/// Gate on Enabled + InstallInfinityHammerTools, then write owned tools YAML.
		/// Safe to write before Infinity Hammer loads; IH will consume it during its startup scan.
		/// </summary>
		internal static void EnsureInstalled()
		{
			ManualLogSource log = SonicWorldToolsPlugin.ModLogger;
			try
			{
				if (PluginConfig.Enabled == null || PluginConfig.InstallInfinityHammerTools == null)
				{
					return;
				}

				if (!PluginConfig.Enabled.Value || !PluginConfig.InstallInfinityHammerTools.Value)
				{
					return;
				}

				string configDir = InfinityHammerBridge.FindConfigDirectory();
				if (string.IsNullOrEmpty(configDir) || !Directory.Exists(configDir))
				{
					log?.LogWarning(
						"BepInEx config path missing; skipped Infinity Hammer tool install.");
					return;
				}

				string toolsDir = Path.Combine(configDir, "tools");
				if (!Directory.Exists(toolsDir))
				{
					Directory.CreateDirectory(toolsDir);
				}

				var options = BuildOptions();
				bool wroteBytes = ToolInstaller.WriteOwnedFile(configDir, preferToolsSubfolder: true, options);
				string destPath = Path.Combine(toolsDir, ToolInstaller.OwnedFileName);

				// Force rewrite if an old stock marker is still on disk.
				if (File.Exists(destPath))
				{
					string onDisk = File.ReadAllText(destPath);
					if (onDisk.IndexOf(ToolInstaller.Marker, StringComparison.OrdinalIgnoreCase) < 0
					    && (onDisk.IndexOf("sonicworldtools-tool", StringComparison.OrdinalIgnoreCase) >= 0
					        || onDisk.IndexOf("Generated by SonicWorldTools", StringComparison.OrdinalIgnoreCase) >= 0
					        || onDisk.IndexOf("Template-Version", StringComparison.OrdinalIgnoreCase) >= 0)
					    && ToolInstaller.IsUpgradeableStockDocument(onDisk))
					{
						string stock = ToolInstaller.BuildOwnedDocument(options);
						File.WriteAllText(destPath, stock);
						wroteBytes = true;
						log?.LogInfo("Forced IH tools YAML upgrade → " + ToolInstaller.Marker);
					}
				}

				if (wroteBytes) log?.LogDebug("[SonicWorldTools] Updated owned Infinity Hammer tool definitions.");
				if (!wroteBytes)
				{
					log?.LogDebug("Owned IH tools file already current: " + destPath);
				}
			}
			catch (Exception ex)
			{
				log?.LogWarning("Infinity Hammer YAML install failed: " + ex.Message);
			}
		}

		private static ToolInstaller.Options BuildOptions()
		{
			string Key(BepInEx.Configuration.ConfigEntry<UnityEngine.KeyCode> entry) => PluginConfig.FormatKeyLabel(entry.Value);
			string Chord(BepInEx.Configuration.ConfigEntry<UnityEngine.KeyCode> modifier, BepInEx.Configuration.ConfigEntry<UnityEngine.KeyCode> key) => modifier.Value == UnityEngine.KeyCode.None ? Key(key) : Key(modifier) + "+" + Key(key);
			return new ToolInstaller.Options
			{
				ModVersion = SonicWorldToolsPlugin.PluginVersion,
				PrecisionDescription = "Click three corners to select. " + Chord(PluginConfig.RefineModifierKey, PluginConfig.AddPieceKey) + " adds; " + Chord(PluginConfig.RefineModifierKey, PluginConfig.ExcludePieceKey) + " excludes. " + PluginConfig.FormatPickUpChordLabel() + " copies; " + Chord(PluginConfig.DismantleModifierKey, PluginConfig.SelectionRemovalKey) + " dismantles; " + Chord(PluginConfig.PermanentDeleteModifierKey, PluginConfig.SelectionRemovalKey) + " deletes.",
				LineDescription = "Sample " + Key(PluginConfig.PieceRepeaterSampleKey) + "; waypoint " + Key(PluginConfig.PieceRepeaterWaypointKey) + "; place " + Chord(PluginConfig.PieceRepeaterPlaceModifier, PluginConfig.PieceRepeaterWaypointKey) + ". Q/E cycles first-piece snaps; " + Chord(PluginConfig.PieceRepeaterJointModifier, PluginConfig.PieceRepeaterWaypointKey) + " snaps a joint; " + Chord(PluginConfig.PieceRepeaterTraceModifier, PluginConfig.PieceRepeaterTraceKey) + " traces a wall. Wheel rotates; " + Key(PluginConfig.PieceRepeaterSpacingModifier) + "+wheel changes gap; " + Key(PluginConfig.PieceRepeaterLevelModifier) + " holds height. " + Key(PluginConfig.PieceRepeaterSettingsHotkey) + " settings and world direction snap; " + Chord(PluginConfig.PieceRepeaterOffsetEditorModifier, PluginConfig.PieceRepeaterSettingsHotkey) + " offsets; Esc exits.",
				ShapeDescription = "Sample " + Key(PluginConfig.PieceRepeaterSampleKey) + "; click a center and move to size. For squares, cursor direction also sets angle. I cycles outline, grid and concentric infill; Shift+wheel changes concentric spacing; " + Chord(PluginConfig.PieceRepeaterPlaceModifier, PluginConfig.PieceRepeaterWaypointKey) + " places. Q cycles circle, square and rectangle. Current size and spacing appear below.",
				ScatterDescription = Key(PluginConfig.ScatterSampleKey) + " samples or removes a prop; " + (PluginConfig.ScatterClearModifier.Value == UnityEngine.KeyCode.None ? "console command clears samples" : Chord(PluginConfig.ScatterClearModifier, PluginConfig.ScatterSampleKey) + " clears samples") + ". Click scatters the sample mix, or the hovered prop when empty.",
				PathHalfWidth = PluginConfig.TerrainPathInitialHalfWidth.Value,
				PathSmoothness = PluginConfig.TerrainPathEdgeSmoothness.Value,
				PathFinishKey = PluginConfig.TerrainPathFinishKey.Value.ToString(),
				PathSmoothKey = PluginConfig.TerrainPathSmoothKey.Value.ToString(),
				PathFinishLabel = PluginConfig.FormatKeyLabel(PluginConfig.TerrainPathFinishKey.Value),
				PathSmoothLabel = PluginConfig.FormatKeyLabel(PluginConfig.TerrainPathSmoothKey.Value),
				LowerHeight = PluginConfig.LowerTerrainInitialHeight.Value,
				LowerSmoothness = PluginConfig.LowerTerrainSmoothness.Value,
				ScatterRadius = PluginConfig.ScatterInitialRadius.Value,
				ForceGrowRadius = PluginConfig.ForceGrowInitialRadius.Value
			};
		}

		/// <summary>
		/// When Enabled or InstallInfinityHammerTools turns off: leave owned YAML on disk, deactivate controller.
		/// </summary>
		internal static void OnIntegrationDisabled()
		{
			PrecisionAreaPipetteController.Instance?.Deactivate();
			PieceRepeaterController.Instance?.Deactivate("integration-disabled");
			SonicWorldToolsPlugin.ModLogger?.LogInfo(
				"SonicWorldTools integration disabled; owned Infinity Hammer YAML left on disk "
				+ "(delete " + ToolInstaller.OwnedFileName + " manually if desired).");
		}
	}
}
