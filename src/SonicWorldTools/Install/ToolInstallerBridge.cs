using System;
using System.IO;
using BepInEx.Logging;
using SonicWorldTools.Config;
using SonicWorldTools.Core;
using SonicWorldTools.Integration;
using SonicWorldTools.Modules.PrecisionAreaPipette;
using SonicWorldTools.Modules.PieceRepeater;

namespace SonicWorldTools.Install
{
	internal static class ToolInstallerBridge
	{
		/// <summary>
		/// Gate on Enabled + InstallInfinityHammerTools, then write owned tools YAML.
		/// Safe to write before Infinity Hammer loads; IH will consume it during its startup scan.
		/// </summary>
		internal static void EnsureInstalled()
		{
			ManualLogSource log = SonicWorldToolsPlugin.ModLogger;
			try
			{
				if (PluginConfig.Enabled == null || PluginConfig.InstallInfinityHammerTools == null)
				{
					return;
				}

				if (!PluginConfig.Enabled.Value || !PluginConfig.InstallInfinityHammerTools.Value)
				{
					return;
				}

				string configDir = InfinityHammerBridge.FindConfigDirectory();
				if (string.IsNullOrEmpty(configDir) || !Directory.Exists(configDir))
				{
					log?.LogWarning(
						"BepInEx config path missing; skipped Infinity Hammer tool install.");
					return;
				}

				string toolsDir = Path.Combine(configDir, "tools");
				if (!Directory.Exists(toolsDir))
				{
					Directory.CreateDirectory(toolsDir);
				}

				bool wroteBytes = ToolInstaller.WriteOwnedFile(configDir, preferToolsSubfolder: true);
				string destPath = Path.Combine(toolsDir, ToolInstaller.OwnedFileName);

				// Force rewrite if an old stock marker is still on disk.
				if (File.Exists(destPath))
				{
					string onDisk = File.ReadAllText(destPath);
					if (onDisk.IndexOf(ToolInstaller.Marker, StringComparison.OrdinalIgnoreCase) < 0
					    && (onDisk.IndexOf("sonicworldtools-tool", StringComparison.OrdinalIgnoreCase) >= 0
					        || onDisk.IndexOf("Generated by SonicWorldTools", StringComparison.OrdinalIgnoreCase) >= 0
					        || onDisk.IndexOf("Template-Version", StringComparison.OrdinalIgnoreCase) >= 0)
					    && ToolInstaller.IsUpgradeableStockDocument(onDisk))
					{
						string stock = ToolInstaller.BuildOwnedDocument();
						File.WriteAllText(destPath, stock);
						wroteBytes = true;
						log?.LogInfo("Forced IH tools YAML upgrade → " + ToolInstaller.Marker);
					}
				}

				log?.LogInfo("[SonicWorldTools] Installed owned Infinity Hammer tool definitions.");
				if (!wroteBytes)
				{
					log?.LogDebug("Owned IH tools file already current: " + destPath);
				}
			}
			catch (Exception ex)
			{
				log?.LogWarning("Infinity Hammer YAML install failed: " + ex.Message);
			}
		}

		/// <summary>
		/// When Enabled or InstallInfinityHammerTools turns off: leave owned YAML on disk, deactivate controller.
		/// </summary>
		internal static void OnIntegrationDisabled()
		{
			PrecisionAreaPipetteController.Instance?.Deactivate();
			PieceRepeaterController.Instance?.Deactivate("integration-disabled");
			SonicWorldToolsPlugin.ModLogger?.LogInfo(
				"SonicWorldTools integration disabled; owned Infinity Hammer YAML left on disk "
				+ "(delete " + ToolInstaller.OwnedFileName + " manually if desired).");
		}
	}
}
