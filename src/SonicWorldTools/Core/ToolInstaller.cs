		/// <summary>
		/// Decide next owned YAML body. Returns true when stock should replace existing bytes.
		/// When preserving user edits, nextYaml is the existing document; caller should write stock to .new.
		/// </summary>
		public static bool WriteOwnedDocument(string existingOwnedYaml, out string nextYaml, out bool writeConflictNew)
		{
			writeConflictNew = false;
			string existing = existingOwnedYaml ?? string.Empty;
			if (ShouldPreserveOwnedDocument(existing))
			{
				nextYaml = NormalizeNewlines(existing).TrimEnd() + Environment.NewLine;
				string stock = NormalizeNewlines(BuildOwnedDocument()).TrimEnd() + "\n";
				string prior = NormalizeNewlines(existing).TrimEnd() + "\n";
				writeConflictNew = !string.Equals(prior, stock, StringComparison.Ordinal);
				return false;
			}

			string stockDoc = NormalizeNewlines(BuildOwnedDocument()).TrimEnd() + "\n";
			string priorDoc = NormalizeNewlines(existing).TrimEnd() + "\n";
			nextYaml = stockDoc.Replace("\n", Environment.NewLine);
			return !string.Equals(priorDoc, stockDoc, StringComparison.Ordinal);
		}

		public static bool ShouldPreserveOwnedDocument(string yaml)
		{
			if (string.IsNullOrWhiteSpace(yaml))
			{
				return false;
			}

			string stock = NormalizeNewlines(BuildOwnedDocument()).TrimEnd();
			string existing = NormalizeNewlines(yaml).TrimEnd();
			if (string.Equals(stock, existing, StringComparison.Ordinal))
			{
				return false;
			}

			if (IsUpgradeableStockDocument(existing))
			{
				return false;
			}

			return true;
		}

		/// <summary>
		/// True for SonicWorldTools-owned stock (marker / Template-Version) without a user edit to the pipette icon.
		/// </summary>
		public static bool IsUpgradeableStockDocument(string yaml)
		{
			if (string.IsNullOrWhiteSpace(yaml))
			{
				return false;
			}

			bool hasMarkerFamily = yaml.IndexOf("sonicworldtools-tool", StringComparison.OrdinalIgnoreCase) >= 0;
			bool hasTemplateVersion = yaml.IndexOf("Template-Version", StringComparison.OrdinalIgnoreCase) >= 0
			                          || yaml.IndexOf("Generated by SonicWorldTools", StringComparison.OrdinalIgnoreCase) >= 0;
			if (!hasMarkerFamily && !hasTemplateVersion)
			{
				return false;
			}

			if (PrimaryToolHasCustomIcon(yaml))
			{
				return false;
			}

			int named = CountNamedToolsInDocument(yaml, ToolName);
			// Renamed docs (no recognized owned name) are not upgradeable stock.
			if (named == 0
			    && yaml.IndexOf("Precision Area Pipette", StringComparison.OrdinalIgnoreCase) < 0)
			{
				return false;
			}

			// Prior stock marker / template without current marker body → rewrite.
			if (yaml.IndexOf(Marker, StringComparison.OrdinalIgnoreCase) < 0)
			{
				return true;
			}

			string stock = NormalizeNewlines(BuildOwnedDocument()).TrimEnd();
			string existing = NormalizeNewlines(yaml).TrimEnd();
			return !string.Equals(stock, existing, StringComparison.Ordinal);
		}

		private static bool PrimaryToolHasCustomIcon(string yaml)
		{
			string[] lines = NormalizeNewlines(yaml).Split('\n');
			var itemLine = new Regex(@"^\s*-\s*name:\s*(.*)$", RegexOptions.IgnoreCase);
			var iconLine = new Regex(@"^\s*icon:\s*(.*?)\s*$", RegexOptions.IgnoreCase);
			bool inPipetteTool = false;
			foreach (string raw in lines)
			{
				string line = raw.TrimEnd('\r');
				Match item = itemLine.Match(line);
				if (item.Success)
				{
					string name = item.Groups[1].Value.Trim().Trim('"', '\'');
					inPipetteTool = string.Equals(name, ToolName, StringComparison.OrdinalIgnoreCase)
					                || name.IndexOf("Precision Area Pipette", StringComparison.OrdinalIgnoreCase) >= 0;
					continue;
				}

				if (!inPipetteTool)
				{
					continue;
				}

				Match icon = iconLine.Match(line);
				if (icon.Success)
				{
					return !string.Equals(icon.Groups[1].Value, "Hammer", StringComparison.OrdinalIgnoreCase);
				}
			}

			return false;
		}

		/// <returns>True if preferred file bytes were written or an alternate was migrated/removed.</returns>
		public static bool WriteOwnedFile(string configRoot, bool preferToolsSubfolder)
		{
			if (string.IsNullOrEmpty(configRoot))
			{
				throw new ArgumentException("configRoot required", nameof(configRoot));
			}

			string toolsDir = Path.Combine(configRoot, "tools");
			if (preferToolsSubfolder && !Directory.Exists(toolsDir))
			{
				Directory.CreateDirectory(toolsDir);
			}

			bool useTools = preferToolsSubfolder && Directory.Exists(toolsDir);
			string preferred = Path.Combine(useTools ? toolsDir : configRoot, OwnedFileName);
			string alternate = Path.Combine(useTools ? configRoot : toolsDir, OwnedFileName);
			// IH's folder watcher loads every file in "tools", regardless of extension.
			// Keep conflict backups at config root so *.yaml.new cannot become a live tool file.
			string safeConflictPath = Path.Combine(configRoot, OwnedFileName + ConflictNewSuffix);
			string nestedConflictPath = preferred + ConflictNewSuffix;
			bool touched = false;
			if (!string.Equals(Path.GetFullPath(nestedConflictPath), Path.GetFullPath(safeConflictPath), StringComparison.OrdinalIgnoreCase)
			    && File.Exists(nestedConflictPath))
			{
				string nestedText = File.ReadAllText(nestedConflictPath, Encoding.UTF8);
				if (!File.Exists(safeConflictPath))
				{
					File.Move(nestedConflictPath, safeConflictPath);
				}
				else if (string.Equals(NormalizeNewlines(File.ReadAllText(safeConflictPath, Encoding.UTF8)), NormalizeNewlines(nestedText), StringComparison.Ordinal))
				{
					File.Delete(nestedConflictPath);
				}
				else
				{
					string archived = safeConflictPath + "." + DateTime.UtcNow.ToString("yyyyMMddHHmmssfff");
					File.Move(nestedConflictPath, archived);
				}
				touched = true;
			}

			ResolveExistingOwnedContent(preferred, alternate, out string existing, out _);

			WriteOwnedDocument(existing, out string next, out bool writeConflictNew);
			string preferredNow = File.Exists(preferred) ? File.ReadAllText(preferred, Encoding.UTF8) : string.Empty;
			if (!File.Exists(preferred)
			    || !string.Equals(NormalizeNewlines(preferredNow), NormalizeNewlines(next), StringComparison.Ordinal))
			{
				AtomicWrite(preferred, next);
				touched = true;
			}

			if (writeConflictNew)
			{
				string stock = NormalizeNewlines(BuildOwnedDocument()).TrimEnd() + Environment.NewLine;
				string existingNew = File.Exists(safeConflictPath) ? File.ReadAllText(safeConflictPath, Encoding.UTF8) : string.Empty;
				if (!string.Equals(NormalizeNewlines(existingNew), NormalizeNewlines(stock), StringComparison.Ordinal))
				{
					AtomicWrite(safeConflictPath, stock);
					touched = true;
				}
			}

			if (File.Exists(alternate)
			    && !string.Equals(Path.GetFullPath(alternate), Path.GetFullPath(preferred), StringComparison.OrdinalIgnoreCase))
			{
				string altText = File.ReadAllText(alternate, Encoding.UTF8);
				string prefText = File.ReadAllText(preferred, Encoding.UTF8);
				if (!string.Equals(NormalizeNewlines(altText), NormalizeNewlines(prefText), StringComparison.Ordinal))
				{
					AtomicWrite(safeConflictPath, altText);
				}

				File.Delete(alternate);
				touched = true;
			}

			return touched;
		}

		public static void ResolveExistingOwnedContent(
			string preferredPath,
			string alternatePath,
			out string existing,
			out string conflictBackupPath)
		{
			existing = string.Empty;
			conflictBackupPath = null;

			bool hasPreferred = File.Exists(preferredPath);
			bool hasAlternate = File.Exists(alternatePath)
			                    && !string.Equals(
				                    Path.GetFullPath(preferredPath),
				                    Path.GetFullPath(alternatePath),
				                    StringComparison.OrdinalIgnoreCase);

			if (!hasPreferred && !hasAlternate)
			{
				return;
			}

			if (hasPreferred && !hasAlternate)
			{
				existing = File.ReadAllText(preferredPath, Encoding.UTF8);
				return;
			}

			if (!hasPreferred && hasAlternate)
			{
				existing = File.ReadAllText(alternatePath, Encoding.UTF8);
				return;
			}

			string preferredText = File.ReadAllText(preferredPath, Encoding.UTF8);
			string alternateText = File.ReadAllText(alternatePath, Encoding.UTF8);
			if (string.Equals(NormalizeNewlines(preferredText), NormalizeNewlines(alternateText), StringComparison.Ordinal))
			{
				existing = preferredText;
				return;
			}

			bool preservePref = ShouldPreserveOwnedDocument(preferredText);
			bool preserveAlt = ShouldPreserveOwnedDocument(alternateText);

			if (preserveAlt && !preservePref)
			{
				existing = alternateText;
			}
			else
			{
				existing = preferredText;
			}

			string preferredDirectory = Path.GetDirectoryName(preferredPath);
			if (string.Equals(Path.GetFileName(preferredDirectory), "tools", StringComparison.OrdinalIgnoreCase))
			{
				preferredDirectory = Directory.GetParent(preferredDirectory)?.FullName ?? preferredDirectory;
			}
			conflictBackupPath = Path.Combine(preferredDirectory, OwnedFileName + ConflictNewSuffix);
		}

		public static int CountNamedToolsInDocument(string yaml, string toolName)
		{
			if (string.IsNullOrEmpty(yaml))
			{
				return 0;
			}

			int count = 0;
			var re = new Regex(
				@"^\s*-\s*name:\s*(?:""|')?" + Regex.Escape(toolName) + @"(?:""|')?\s*$",
				RegexOptions.Multiline | RegexOptions.IgnoreCase);
			foreach (Match m in re.Matches(yaml))
			{
				count++;
			}

			return count;
		}

		public static bool OwnedEntryHasActivateCommand(string yaml)
		{
			return OwnedEntryHasCommand(yaml, ToolName, ActivateCommand);
		}

		public static bool OwnedEntryHasCommand(string yaml, string toolName, string command)
		{
			if (string.IsNullOrEmpty(yaml))
			{
				return false;
			}

			string[] lines = NormalizeNewlines(yaml).Split('\n');
			bool inOurTool = false;
			var nameRe = new Regex(
				@"^\s*-\s*name:\s*(?:""|')?" + Regex.Escape(toolName) + @"(?:""|')?\s*$",
				RegexOptions.IgnoreCase);
			var anyItem = new Regex(@"^\s*-\s*name:\s*\S");
			foreach (string raw in lines)
			{
				string line = raw.TrimEnd('\r');
				if (nameRe.IsMatch(line))
				{
					inOurTool = true;
					continue;
				}

				if (inOurTool && anyItem.IsMatch(line))
				{
					inOurTool = false;
				}

				if (inOurTool && line.IndexOf("command:", StringComparison.OrdinalIgnoreCase) >= 0
				    && line.IndexOf(command, StringComparison.OrdinalIgnoreCase) >= 0)
				{
					return true;
				}
			}

			return false;
		}

		public static bool LooksLikeEquipmentDictionary(string yaml)
		{
			if (string.IsNullOrEmpty(yaml))
			{
				return false;
			}

			return Regex.IsMatch(
				NormalizeNewlines(yaml),
				@"(?m)^[A-Za-z][A-Za-z0-9_]*:\s*$",
				RegexOptions.None);
		}

		private static void AtomicWrite(string path, string contents)
		{
			string dir = Path.GetDirectoryName(path);
			if (!string.IsNullOrEmpty(dir) && !Directory.Exists(dir))
			{
				Directory.CreateDirectory(dir);
			}

			string temp = path + ".tmp";
			File.WriteAllText(temp, contents, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
			if (File.Exists(path))
			{
				File.Replace(temp, path, null);
			}
			else
			{
				File.Move(temp, path);
			}
		}

		private static string NormalizeNewlines(string s)
		{
			return (s ?? string.Empty).Replace("\r\n", "\n").Replace('\r', '\n');
		}
