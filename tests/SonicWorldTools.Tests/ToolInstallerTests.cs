using System.IO;
using SonicWorldTools.Core;
using Xunit;

namespace SonicWorldTools.Tests
{
	public sealed class ToolInstallerTests
	{
		[Fact]
		public void BuildOwnedDocument_HasExpectedStockShape()
		{
			string doc = ToolInstaller.BuildOwnedDocument();
			Assert.True(ToolInstaller.LooksLikeEquipmentDictionary(doc));
			Assert.Contains("hammer:", doc);
			Assert.Contains("# Generated by SonicWorldTools", doc);
			Assert.Contains("# Template-Version: 1", doc);
			Assert.Contains(ToolInstaller.Marker, doc);
			Assert.Equal(1, ToolInstaller.CountNamedToolsInDocument(doc, ToolInstaller.ToolName));
			Assert.Contains(ToolInstaller.ActivateCommand, doc);
			Assert.Contains("instant: true", doc);
			Assert.Contains("icon: Hammer", doc);
			Assert.True(ToolInstaller.OwnedEntryHasActivateCommand(doc));
		}

		[Fact]
		public void WriteOwnedDocument_Idempotent_ForStock()
		{
			ToolInstaller.WriteOwnedDocument("", out string first, out bool conflictNew);
			Assert.False(conflictNew);
			bool changed = ToolInstaller.WriteOwnedDocument(first, out string second, out bool conflictNew2);
			Assert.False(changed);
			Assert.False(conflictNew2);
			Assert.Equal(Normalize(first), Normalize(second));
		}

		[Fact]
		public void WriteOwnedDocument_UpgradesOldUntouchedGenerated()
		{
			string old =
				"# Generated by SonicWorldTools\n"
				+ "# Template-Version: 1\n"
				+ "# sonicworldtools-tool-v0 — owned by SonicWorldTools\n"
				+ "hammer:\n"
				+ "- name: SonicWorldTools - Precision Area Pipette\n"
				+ "  description: |-\n"
				+ "    M0 scaffold — precision area selection pipette (coming in a later milestone).\n"
				+ "  icon: Hammer\n"
				+ "  instant: true\n"
				+ "  command: sonic_precision_pipette\n"
				+ "  tabIndex: 0\n";

			Assert.True(ToolInstaller.IsUpgradeableStockDocument(old));
			Assert.False(ToolInstaller.ShouldPreserveOwnedDocument(old));
			bool changed = ToolInstaller.WriteOwnedDocument(old, out string next, out bool conflictNew);
			Assert.True(changed);
			Assert.False(conflictNew);
			Assert.Contains(ToolInstaller.Marker, next);
			Assert.Contains("Ctrl+Del dismantle, Shift+Del delete", next);
		}

		[Fact]
		public void WriteOwnedDocument_PreservesUserEditedIcon_AndWritesConflictFlag()
		{
			string edited = ToolInstaller.BuildOwnedDocument().Replace("icon: Hammer", "icon: Pickaxe");
			Assert.True(ToolInstaller.ShouldPreserveOwnedDocument(edited));
			bool changed = ToolInstaller.WriteOwnedDocument(edited, out string next, out bool conflictNew);
			Assert.False(changed);
			Assert.True(conflictNew);
			Assert.Contains("icon: Pickaxe", next);
		}

		[Fact]
		public void WriteOwnedFile_FirstInstall_CreatesToolsFolderAndFile()
		{
			string dir = Path.Combine(Path.GetTempPath(), "swt-ih-first-" + Path.GetRandomFileName());
			Directory.CreateDirectory(dir);
			try
			{
				Assert.False(Directory.Exists(Path.Combine(dir, "tools")));
				bool touched = ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true);
				Assert.True(touched);
				string toolsOwned = Path.Combine(dir, "tools", ToolInstaller.OwnedFileName);
				Assert.True(File.Exists(toolsOwned));
				string text = File.ReadAllText(toolsOwned);
				Assert.Contains(ToolInstaller.Marker, text);
				Assert.Contains(ToolInstaller.ActivateCommand, text);
			}
			finally
			{
				Directory.Delete(dir, true);
			}
		}

		[Fact]
		public void WriteOwnedFile_AlreadyCurrent_DoesNotRewrite()
		{
			string dir = Path.Combine(Path.GetTempPath(), "swt-ih-current-" + Path.GetRandomFileName());
			Directory.CreateDirectory(dir);
			string tools = Path.Combine(dir, "tools");
			Directory.CreateDirectory(tools);
			try
			{
				string toolsOwned = Path.Combine(tools, ToolInstaller.OwnedFileName);
				File.WriteAllText(toolsOwned, ToolInstaller.BuildOwnedDocument());
				long ticksBefore = File.GetLastWriteTimeUtc(toolsOwned).Ticks;

				bool touched = ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true);
				Assert.False(touched);
				Assert.Equal(ticksBefore, File.GetLastWriteTimeUtc(toolsOwned).Ticks);
			}
			finally
			{
				Directory.Delete(dir, true);
			}
		}

		[Fact]
		public void WriteOwnedFile_UserModified_PreservesAndWritesDotNew()
		{
			string dir = Path.Combine(Path.GetTempPath(), "swt-ih-user-" + Path.GetRandomFileName());
			Directory.CreateDirectory(dir);
			string tools = Path.Combine(dir, "tools");
			Directory.CreateDirectory(tools);
			try
			{
				string toolsOwned = Path.Combine(tools, ToolInstaller.OwnedFileName);
				string edited = ToolInstaller.BuildOwnedDocument().Replace("icon: Hammer", "icon: Pickaxe");
				File.WriteAllText(toolsOwned, edited);

				bool touched = ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true);
				Assert.True(touched);
				Assert.Contains("icon: Pickaxe", File.ReadAllText(toolsOwned));
				string newPath = Path.Combine(dir, ToolInstaller.OwnedFileName + ToolInstaller.ConflictNewSuffix);
				Assert.True(File.Exists(newPath));
				Assert.Contains("icon: Hammer", File.ReadAllText(newPath));
				Assert.Contains(ToolInstaller.Marker, File.ReadAllText(newPath));
			}
			finally
			{
				Directory.Delete(dir, true);
			}
		}

		[Fact]
		public void WriteOwnedFile_MigratesRootOwnedToTools()
		{
			string dir = Path.Combine(Path.GetTempPath(), "swt-ih-migrate-" + Path.GetRandomFileName());
			Directory.CreateDirectory(dir);
			try
			{
				string rootOwned = Path.Combine(dir, ToolInstaller.OwnedFileName);
				File.WriteAllText(rootOwned, ToolInstaller.BuildOwnedDocument());

				bool touched = ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true);
				Assert.True(touched);
				Assert.True(File.Exists(Path.Combine(dir, "tools", ToolInstaller.OwnedFileName)));
				Assert.False(File.Exists(rootOwned));
			}
			finally
			{
				Directory.Delete(dir, true);
			}
		}

		[Fact]
		public void WriteOwnedFile_DuplicateExecution_Stable()
		{
			string dir = Path.Combine(Path.GetTempPath(), "swt-ih-dup-" + Path.GetRandomFileName());
			Directory.CreateDirectory(dir);
			try
			{
				Assert.True(ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true));
				Assert.False(ToolInstaller.WriteOwnedFile(dir, preferToolsSubfolder: true));
				string path = Path.Combine(dir, "tools", ToolInstaller.OwnedFileName);
				Assert.Equal(1, ToolInstaller.CountNamedToolsInDocument(File.ReadAllText(path), ToolInstaller.ToolName));
			}
			finally
			{
				Directory.Delete(dir, true);
			}
		}

		[Fact]
		public void PureApi_WorksWithoutInfinityHammerPath()
		{
			// Bridge skip is integration; pure API only needs a config root.
			string doc = ToolInstaller.BuildOwnedDocument();
			Assert.False(string.IsNullOrWhiteSpace(doc));
			Assert.True(ToolInstaller.WriteOwnedDocument(null, out string next, out _));
			Assert.Contains(ToolInstaller.Marker, next);
		}

		private static string Normalize(string s) => (s ?? "").Replace("\r\n", "\n").Trim();
	}
}
